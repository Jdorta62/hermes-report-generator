"""Relocate hand-written .api files into .claude/api/ and maintain INDEX.api.

Deterministic port of the former `diego-relocate` agent plus §2-§3 of
`.claude/api-spec.md`:

- every `<path>.api` left beside its `<path>.py` source (outside hidden
  directories) is moved to `.claude/api/`, mirroring the source tree with a
  leading `src/` stripped; its content is never altered;
- `.api` files under `.claude/api/` whose source `.py` no longer exists are
  deleted when they carry the header marker (kept with a warning otherwise);
- `INDEX.api` is rebuilt from the `.api` tree: header and legend byte-exact,
  one `@mod` line per module sorted by dotted name, summary copied verbatim;
- `STATUS.md` lines for modules without a `.api` file are removed; no other
  line is ever added or edited.

Warnings go to stderr and never change the exit code.
"""

import argparse
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

MARKER = "# apigen-format: 2 | generated by apigen, do not edit"
# Ownership check: files from any format version count as generated.
MARKER_RE = re.compile(r"# apigen-format: \d+ \| generated by apigen, do not edit")
LEGEND = (
  "# LEGEND",
  "# kinds: C=class A=abstract D=dataclass I=protocol E=enum",
  "# members: a=attr p=property m=method cm=classmethod sm=staticmethod"
  " am=abstractmethod f=function k=constant",
  "# flags: ^=override [ro]=read-only [frozen]=frozen dataclass ?=unknown/unresolved",
  "# contract: !=raises ~=effects(io|net|mut|gpu|proc) ::=summary"
  " req:=precondition ex:=usage reg:=registry[key] main:=CLI entry",
  "# @reexport=public name imported from another module",
  "# @deps=project modules imported @ext=third-party packages imported",
)
API_DIR = Path(".claude") / "api"
INDEX_NAME = "INDEX.api"
STATUS_NAME = "STATUS.md"
SKIPPED_DIRS = {"node_modules", "__pycache__", "build", "dist"}


@dataclass(frozen=True)
class Module:
  """One module documented under `.claude/api/`."""

  dotted: str
  rel_path: str
  summary: str | None


@dataclass
class Report:
  """What a relocation run did."""

  moved: list[tuple[Path, Path]] = field(default_factory=list)
  deleted: list[Path] = field(default_factory=list)
  warnings: list[str] = field(default_factory=list)
  index_updated: bool = False
  status_removed: list[str] = field(default_factory=list)


def warn(report: Report, message: str) -> None:
  report.warnings.append(message)


def dotted_name(api_rel: Path) -> str:
  """Dotted module name of a path relative to `.claude/api/` (spec §2)."""
  parts = list(api_rel.with_suffix("").parts)
  if parts and parts[-1] == "__init__":
    parts.pop()
  return ".".join(parts)


def mirror_path(source_rel: Path) -> Path:
  """Path under `.claude/api/` for an .api file beside a source (spec §2)."""
  parts = source_rel.parts
  if parts and parts[0] == "src":
    parts = parts[1:]
  return Path(*parts)


def read_lines(path: Path) -> list[str]:
  return path.read_text(encoding="utf-8").splitlines()


def has_marker(lines: list[str]) -> bool:
  """Whether the first line is the header marker of any format version."""
  return bool(lines) and MARKER_RE.fullmatch(lines[0]) is not None


def mod_line(lines: list[str]) -> tuple[str, str | None] | None:
  """Parse the first `@mod <dotted>[ :: <summary>]` line."""
  for line in lines:
    if line.startswith("@mod "):
      body = line[len("@mod ") :]
      name, sep, summary = body.partition(" :: ")
      return name.strip(), (summary if sep else None)
  return None


def find_loose_api_files(root: Path) -> list[Path]:
  """`.api` files outside hidden directories, sorted for determinism."""
  found: list[Path] = []
  for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = sorted(
      d for d in dirnames if not d.startswith(".") and d not in SKIPPED_DIRS
    )
    for filename in sorted(filenames):
      if filename.endswith(".api"):
        found.append(Path(dirpath) / filename)
  return found


def source_exists(root: Path, api_rel: Path) -> bool:
  """Whether the `.py` source of a module under `.claude/api/` still exists."""
  py_rel = api_rel.with_suffix(".py")
  return (root / "src" / py_rel).is_file() or (root / py_rel).is_file()


def relocate(root: Path, report: Report) -> None:
  api_root = root / API_DIR
  for loose in find_loose_api_files(root):
    rel = loose.relative_to(root)
    if not loose.with_suffix(".py").is_file():
      warn(report, f"{rel}: no matching .py beside it; left in place")
      continue
    lines = read_lines(loose)
    if not has_marker(lines):
      warn(report, f"{rel}: missing SPEC header marker; relocated anyway")
    target_rel = mirror_path(rel)
    expected = dotted_name(target_rel)
    parsed = mod_line(lines)
    if parsed is None:
      warn(report, f"{rel}: no @mod line")
    elif parsed[0] != expected:
      warn(report, f"{rel}: @mod {parsed[0]} does not match path ({expected})")
    target = api_root / target_rel
    if target.is_file():
      existing = read_lines(target)
      if not has_marker(existing):
        warn(report, f"{API_DIR / target_rel}: overwriting a file without the marker")
    target.parent.mkdir(parents=True, exist_ok=True)
    os.replace(loose, target)
    report.moved.append((rel, API_DIR / target_rel))


def prune_stale(root: Path, report: Report) -> None:
  api_root = root / API_DIR
  for api_file in sorted(api_root.rglob("*.api")):
    api_rel = api_file.relative_to(api_root)
    if api_rel == Path(INDEX_NAME) or source_exists(root, api_rel):
      continue
    lines = read_lines(api_file)
    if has_marker(lines):
      api_file.unlink()
      report.deleted.append(API_DIR / api_rel)
      remove_empty_dirs(api_file.parent, api_root)
    else:
      warn(report, f"{API_DIR / api_rel}: source is gone but file has no marker; kept")


def remove_empty_dirs(directory: Path, stop: Path) -> None:
  while directory != stop and directory.is_dir() and not any(directory.iterdir()):
    directory.rmdir()
    directory = directory.parent


def collect_modules(root: Path) -> list[Module]:
  """Modules with a `.api` under `.claude/api/` and an existing source."""
  api_root = root / API_DIR
  modules: list[Module] = []
  if not api_root.is_dir():
    return modules
  for api_file in sorted(api_root.rglob("*.api")):
    api_rel = api_file.relative_to(api_root)
    if api_rel == Path(INDEX_NAME) or not source_exists(root, api_rel):
      continue
    parsed = mod_line(read_lines(api_file))
    summary = parsed[1] if parsed else None
    modules.append(Module(dotted_name(api_rel), api_rel.as_posix(), summary))
  modules.sort(key=lambda module: module.dotted)
  return modules


def render_index(modules: list[Module]) -> str:
  lines = [MARKER, *LEGEND]
  if modules:
    lines.append("")
    for module in modules:
      summary = f" :: {module.summary}" if module.summary else ""
      lines.append(f"@mod {module.dotted}{summary} -> {module.rel_path}")
  return "\n".join(lines) + "\n"


def status_module(line: str) -> str | None:
  """Dotted module of a STATUS.md line (`<dotted>  :: ...`), if it is one."""
  name, sep, _ = line.partition("::")
  name = name.strip()
  if not sep or not name or " " in name:
    return None
  return name


def prune_status(root: Path, modules: list[Module]) -> list[str]:
  """Drop STATUS.md lines whose module has no .api; return removed modules."""
  status = root / API_DIR / STATUS_NAME
  if not status.is_file():
    return []
  known = {module.dotted for module in modules}
  text = status.read_text(encoding="utf-8")
  kept: list[str] = []
  removed: list[str] = []
  for line in text.splitlines(keepends=True):
    name = status_module(line)
    if name is not None and name not in known:
      removed.append(name)
    else:
      kept.append(line)
  if removed:
    status.write_text("".join(kept), encoding="utf-8")
  return removed


def write_if_changed(path: Path, content: str) -> bool:
  if path.is_file() and path.read_text(encoding="utf-8") == content:
    return False
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(content, encoding="utf-8", newline="\n")
  return True


def run(root: Path) -> Report:
  report = Report()
  relocate(root, report)
  prune_stale(root, report)
  modules = collect_modules(root)
  report.index_updated = write_if_changed(
    root / API_DIR / INDEX_NAME, render_index(modules)
  )
  report.status_removed = prune_status(root, modules)
  return report


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  parser.add_argument("--root", type=Path, default=Path.cwd(), help="project root")
  args = parser.parse_args(argv)
  root: Path = args.root.resolve()
  report = run(root)
  for source, target in report.moved:
    print(f"moved {source} -> {target}")
  for path in report.deleted:
    print(f"deleted stale {path}")
  if report.index_updated:
    print(f"updated {API_DIR / INDEX_NAME}")
  for name in report.status_removed:
    print(f"removed orphan STATUS.md line: {name}")
  for message in report.warnings:
    print(f"relocate: warning: {message}", file=sys.stderr)
  return 0


if __name__ == "__main__":
  sys.exit(main())
